    /**
     * Generate a memory cue for the identified person.
     * In template mode this is instant (<1 ms).  Returns Pair<cue text, token count>.
     * Token count is 0 in template mode; it will reflect real token counts once the
     * neural runner is enabled.
     * [stage: llm_generation]
     */
    fun generate(name: String, relationship: String, summaries: List<String>): Pair<String, Int> {
        LatencyTracker.markStart(LatencyTracker.STAGE_LLM_GENERATION)
        val cue = buildTemplateCue(name, relationship, summaries)
        LatencyTracker.markEnd(LatencyTracker.STAGE_LLM_GENERATION)
        Log.d(TAG, "Generated cue (template): $cue")
        return Pair(cue, 0)
    }

    /**
     * Warm, context-aware template sentence.
     * Only uses a summary as context if it was typed by the user — auto-generated
     * presence-log entries ("X was present on ... for Y seconds.") are skipped
     * because they add no useful memory context to the spoken cue.
     */
    private fun buildTemplateCue(name: String, relationship: String, summaries: List<String>): String {
        val meaningful = summaries.firstOrNull { s ->
            s.isNotBlank() && !isAutoGenerated(s)
        }
        return if (meaningful != null) {
            "This is $name, your $relationship. $meaningful"
        } else {
            "This is $name, your $relationship."
        }
    }

    /** Returns true for the fallback presence-log format saved when user presses Skip. */
    private fun isAutoGenerated(summary: String): Boolean =
        summary.contains("was present on") && summary.trimEnd().endsWith("seconds.")

