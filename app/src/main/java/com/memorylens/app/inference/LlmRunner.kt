/**
 * Cue generator for the pipeline.
 *
 * CURRENT MODE — Template only (hackathon MVP on MediaTek A34).
 * [generate] builds a warm, natural sentence from name, relationship, and the most
 * recent conversation summary.  Latency is measured so the dashboard row updates
 * correctly (it will show < 1 ms in template mode).
